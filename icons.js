function pixelSvg(rows) {
  let rects = "";
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; ) {
      const ch = row[x];
      let end = x + 1;
      while (end < row.length && row[end] === ch) end++;
      if (ch !== ".") rects += `<rect x="${x}" y="${y}" width="${end - x}" height="1" fill="${BADGE_COLORS[ch]}"/>`;
      x = end;
    }
  });
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16" shape-rendering="crispEdges" aria-hidden="true">${rects}</svg>`;
}

const iconCache = {};
// solo — іконка без тексту поруч (без відступу справа)
function iconHtml(name, solo = true) {
  const rows = ICONS[name] || GLYPHS[name];
  if (!rows) return "";
  const svg = (iconCache[name] ??= pixelSvg(rows));
  return `<span class="px${solo ? " solo" : ""}">${svg}</span>`;
}

// Іконка + текст одним вузлом: el() з app.js для тексту, щоб не вставляти чужий текст як HTML
function icon(name, text) {
  const span = document.createElement("span");
  span.className = "with-px";
  span.innerHTML = iconHtml(name, text === undefined);
  if (text !== undefined) span.append(text);
  return span;
}

function hydrateIcons(root = document) {
  root.querySelectorAll("[data-icon]").forEach((node) => {
    if (!node.querySelector(":scope > .px")) {
      node.insertAdjacentHTML("afterbegin", iconHtml(node.dataset.icon, !node.textContent.trim()));
    }
  });
}

